/**
 * The voice library catalogue.
 *
 * Every entry below is a *real*, human-recorded, non-neural speech-synthesis
 * database that was investigated for Vocalis. Nothing here is generated, cloned or
 * converted from another voice: these are recordings of people, published by the
 * projects named, for exactly this purpose.
 *
 * Compatibility classes, as required by docs/VOICE_LIBRARY.md:
 *
 *   A  directly compatible      — convert with a script we already run, no change to the audio
 *   B  compatible after an adapter — same idea, details discovered at install time
 *   C  needs a separate front end  — the audio is right, the language is not English
 *   D  not compatible           — format or licence rules it out; kept visible, never installed
 *
 * `install: null` means there is no installer for that voice yet. It is not a
 * claim that the voice is bad, and it never means "hide it from the user".
 *
 * This file is data, not logic. It was assembled from the project pages and
 * archives named in each entry; see docs/VOICE_LIBRARY.md for the verification
 * notes and the exact date of each check.
 *
 * Original Vocalis code.
 */

export type VoiceCompatibility = 'A' | 'B' | 'C' | 'D';

export type CommercialUse = 'permitted' | 'restricted' | 'prohibited' | 'unknown';

export interface VoiceLicence {
  name: string;
  url: string;
  commercialUse: CommercialUse;
  redistribution: string;
  modification: string;
  attribution: string;
}

/**
 * How an installer turns the published archive into a Vocalis pack. The recipe is
 * deliberately declarative: scripts/install_voice.py reads it and does the work, so
 * adding a compatible voice never means adding code to the application.
 */
export type InstallRecipe =
  | {
      kind: 'arctic-archive';
      url: string;
      /** The CMU ARCTIC speaker code inside the archive (cmu_us_<speaker>_arctic). */
      speaker: string;
    }
  | {
      kind: 'festival-est';
      url: string;
      archive: 'tar.gz' | 'tar.bz2';
      /** Path of the EST index inside the archive, a nested tarball, or "auto". */
      dicPath: string;
      /** Path of the waveform directory or of a nested tarball of waveforms. */
      wavPath: string;
    };

export interface VoiceCandidate {
  id: string;
  displayName: string;
  language: string;
  accent: string;
  gender: 'Male' | 'Female' | 'Unknown';
  sourceProject: string;
  sourceUrl: string;
  downloadUrl?: string;
  downloadBytes?: number;
  /** Human-readable download size, as published by the project. */
  downloadLabel: string;
  originalFormat: string;
  licence: VoiceLicence;
  compatibility: VoiceCompatibility;
  compatibilityNote: string;
  install: InstallRecipe | null;
  notes?: string;
}

